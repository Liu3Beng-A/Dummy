"""Generate the shared seven-color rainbow PWM lookup tables (no dependencies).

Seven sRGB design anchors are interpolated in Oklab, then converted to linear
RGB/PWM. This is a standard-RGB approximation, not measured LED calibration.
Out-of-gamut negative channels are clipped and excess peaks scaled together.
Runtime only interpolates a 112-entry Q8 table; no color-space math runs on MCU.
Color conversion: https://bottosson.github.io/posts/oklab/
Run --check in verification, or --write after intentionally changing the design.
"""
import argparse
import math
from pathlib import Path


ANCHORS = (
    ("red", (255, 0, 0)),
    ("orange", (255, 127, 0)),
    ("yellow", (255, 255, 0)),
    ("green", (0, 255, 0)),
    ("cyan", (0, 255, 255)),
    ("blue", (0, 0, 255)),
    ("violet", (139, 0, 255)),
)
SAMPLE_COUNT = 112
SCALE = 256


def decode_srgb(value):
    value /= 255
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def to_oklab(rgb):
    r, g, b = rgb
    l = (0.4122214708*r + 0.5363325363*g + 0.0514459929*b) ** (1/3)
    m = (0.2119034982*r + 0.6806995451*g + 0.1073969566*b) ** (1/3)
    s = (0.0883024619*r + 0.2817188376*g + 0.6299787005*b) ** (1/3)
    return (0.2104542553*l + 0.7936177850*m - 0.0040720468*s,
            1.9779984951*l - 2.4285922050*m + 0.4505937099*s,
            0.0259040371*l + 0.7827717662*m - 0.8086757660*s)


def from_oklab(lab):
    light, a, b = lab
    l = (light + 0.3963377774*a + 0.2158037573*b) ** 3
    m = (light - 0.1055613458*a - 0.0638541728*b) ** 3
    s = (light - 0.0894841775*a - 1.2914855480*b) ** 3
    return (4.0767416621*l - 3.3077115913*m + 0.2309699292*s,
            -1.2684380046*l + 2.6097574011*m - 0.3413193965*s,
            -0.0041960863*l - 0.7034186147*m + 1.7076147010*s)


def make_palette():
    linear = [tuple(map(decode_srgb, rgb)) for _, rgb in ANCHORS]
    labs = [to_oklab(rgb) for rgb in linear]
    lengths = [math.dist(lab, labs[(index+1) % len(labs)]) for index, lab in enumerate(labs)]
    total = sum(lengths)
    result = []
    # Allocate space by perceptual path length, not seven hard equal blocks.
    # Short orange/yellow or blue/violet intervals do not linger while longer
    # green/yellow or violet/red intervals rush by. The last leg closes to red.
    for sample in range(SAMPLE_COUNT):
        distance = total * sample / SAMPLE_COUNT
        index = 0
        while index < len(lengths)-1 and distance >= lengths[index]:
            distance -= lengths[index]
            index += 1
        first = labs[index]
        second = labs[(index + 1) % len(labs)]
        if distance == 0:
            rgb = linear[index]
        else:
            t = distance / lengths[index]
            rgb = from_oklab(tuple(a + (b-a)*t for a, b in zip(first, second)))
            rgb = tuple(max(0.0, value) for value in rgb)
            peak = max(1.0, *rgb)
            rgb = tuple(value / peak for value in rgb)
        result.append(tuple(int(value * 255 * SCALE + 0.5) for value in rgb))
    assert len(result) == SAMPLE_COUNT
    assert all(0 <= channel <= 255*SCALE for pixel in result for channel in pixel)
    return tuple(result)


def outputs(repo):
    palette = make_palette()
    description = "red / orange / yellow / green / cyan / blue / violet / red"
    header = ("// Generated by tools/generate_rgb_rainbow.py; edit the generator.\n"
              "// " + description + "; linear RGB/PWM in Q8 units.\n"
              "#ifndef DUMMY_RGB_RAINBOW_HPP\n#define DUMMY_RGB_RAINBOW_HPP\n"
              "#include <cstdint>\nnamespace RgbRainbow {\n"
              f"constexpr unsigned COUNT = {len(palette)}, SCALE = {SCALE};\n"
              "constexpr uint16_t COLORS[COUNT][3] = {\n"
              + "".join("    {%d, %d, %d},\n" % rgb for rgb in palette)
              + "};\n}\n#endif\n")
    python = ('"""Generated by tools/generate_rgb_rainbow.py; edit the generator.\n'
              + description + '; linear RGB/PWM in Q8 units.\n"""\n'
              + f"RAINBOW_SCALE = {SCALE}\nRAINBOW_PALETTE = (\n"
              + "".join("    (%d, %d, %d),\n" % rgb for rgb in palette)
              + ")\n")
    return {
        repo / "firmware_new/dummy-ref-core-fw/Bsp/gpio/rgb_rainbow.hpp": header,
        repo / "Dummy上位机/app/core/rgb_rainbow.py": python,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs(Path(__file__).resolve().parents[1]).items():
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        else:
            assert path.read_text(encoding="utf-8") == content, f"Stale generated table: {path}"
        print(("Generated: " if args.write else "Matched: ") + str(path))


if __name__ == "__main__":
    main()
